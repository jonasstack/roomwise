type Key = keyof typeof de;

/** English: loaded on demand (src/i18n-en.ts), until then the German text stands in */
let en: Partial<Record<Key, string>> | null = null;
let enLoading: Promise<void> | null = null;
const langListeners = new Set<() => void>();

/** Called once the texts of a newly chosen language are there (re-render): returns how to stop listening */
export function onLanguageLoaded(cb: () => void): () => void {
  langListeners.add(cb);
  return () => langListeners.delete(cb);
}

function loadEnglish(): Promise<void> {
  enLoading ??= import('./i18n-en').then(
    (m) => {
      en = m.en;
      for (const cb of [...langListeners]) cb();
    },
    () => {
      enLoading = null; // offline for a moment: tried again with the next language change
    },
  );
  return enLoading;
}

/** Resolves once the texts of the current language are loaded (tests, first render) */
export const languageReady = (): Promise<void> => (lang === 'en' && !en ? loadEnglish() : Promise.resolve());

let lang: 'de' | 'en' = 'de';

export function setLanguage(language: string | undefined) {
  lang = language?.toLowerCase().startsWith('de') ? 'de' : 'en';
  if (lang === 'en' && !en) void loadEnglish();
}

export const getLanguage = () => lang;

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s = (lang === 'en' ? en?.[key] : undefined) ?? de[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

// formatters are costly to create and every label re-render formats numbers: one per language and digits
const numberFormats = new Map<string, Intl.NumberFormat>();
export function formatNumber(n: number, digits = 1): string {
  const key = `${lang}|${digits}`;
  let f = numberFormats.get(key);
  if (!f) {
    f = new Intl.NumberFormat(lang === 'de' ? 'de-DE' : 'en-US', { minimumFractionDigits: digits, maximumFractionDigits: digits });
    numberFormats.set(key, f);
  }
  return f.format(n);
}

const clockFormats = new Map<string, Intl.DateTimeFormat>();
/** Clock time in the card's language ("17:42", "5:42 PM") */
export function formatClock(d: Date): string {
  let f = clockFormats.get(lang);
  if (!f) {
    f = new Intl.DateTimeFormat(lang === 'de' ? 'de-DE' : 'en-US', { hour: 'numeric', minute: '2-digit' });
    clockFormats.set(lang, f);
  }
  return f.format(d);
}

